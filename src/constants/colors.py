"""Color definitions"""

from __future__ import annotations

from enum import Enum


class Color(tuple, Enum):
    # Basic colors
    WHITE = (0xFF, 0xFF, 0xFF, 0xFF)

    # Background colors
    TRANSLUCENT_BLACK = (0x00, 0x00, 0x00, 0xB0)

    # Exception colors
    IMPOSSIBLE = (0xA0, 0xA0, 0xA0, 0xFF)

    # Attack colors
    PLAYER_ATTACK = (0xFF, 0x90, 0xFF, 0xFF)
    ENEMY_ATTACK = (0xFF, 0x70, 0x70, 0xFF)

    # Other colors
    AMERICAN_ROSE = (0xFF, 0x03, 0x3E, 0xFF)
    RUBINE_RED = (0xD1, 0x00, 0x56, 0xFF)
