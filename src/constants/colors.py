    # Basic colors
    White = (0xFF, 0xFF, 0xFF, 0xFF)

    # Background colors
    TranslucentBlack = (0x00, 0x00, 0x00, 0xB0)

    # Exception colors
    Impossible = (0xA0, 0xA0, 0xA0, 0xFF)

    # Attack colors
    PlayerAttack = (0xFF, 0x90, 0xFF, 0xFF)
    EnemyAttack = (0xFF, 0x70, 0x70, 0xFF)

    # Other colors
    AmericanRose = (0xFF, 0x03, 0x3E, 0xFF)
    RUBINE_RED = (0xD1, 0x00, 0x56, 0xFF)
